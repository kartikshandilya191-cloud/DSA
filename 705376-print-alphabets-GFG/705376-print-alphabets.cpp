// function should print the alphabets
// from c1 to c2 (space separated)
// No need to print the new line
// The new line will be printed by the
// driver's code.

void alphabets(char c1, char c2) {
    for(char ch=c1; ch<=c2; ch++){
        cout << ch << " ";
    }
}

